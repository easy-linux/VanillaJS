/**
 * Модуль для управления Fiber-архитектурой.
 * 
 * Fiber - это структура данных, представляющая узел в дереве компонентов.
 * Каждый экземпляр компонента имеет свой Fiber-узел, который хранит:
 * - Состояние компонента (хуки)
 * - Связи с родителем, детьми и siblings
 * - Метаданные для reconciliation (сопоставления старого и нового дерева)
 * 
 * Стек контекста позволяет хукам (useState, useMemo) находить свой Fiber-узел
 * во время рендеринга компонента.
 */

// Текущий активный Fiber-узел в контексте рендеринга
// Используется хуками для доступа к своему хранилищу состояния
let currentFiber = null;

// Стек Fiber-узлов для поддержки вложенных компонентов
// Когда компонент A рендерит компонент B, A сохраняется в стеке,
// а B становится currentFiber. После рендеринга B восстанавливается A.
const fiberStack = [];

/**
 * Устанавливает новый Fiber-узел как текущий в контексте.
 * Сохраняет предыдущий текущий узел в стек для последующего восстановления.
 * 
 * Используется при входе в компонент для рендеринга.
 * 
 * @param {Fiber} fiber - Fiber-узел, который становится текущим
 */
export function pushCurrentFiber(fiber) {
  // Сохраняем текущий узел в стек (может быть null для корневого компонента)
  fiberStack.push(currentFiber);
  // Устанавливаем новый узел как текущий
  currentFiber = fiber;
}

/**
 * Восстанавливает предыдущий Fiber-узел из стека.
 * Используется при выходе из компонента после рендеринга.
 * 
 * @returns {Fiber|null} - Восстановленный Fiber-узел или null, если стек пуст
 */
export function popCurrentFiber() {
  // Восстанавливаем предыдущий узел из стека
  // Если стек пуст, возвращаем null (используем оператор ??)
  currentFiber = fiberStack.pop() ?? null;
}

/**
 * Возвращает текущий активный Fiber-узел.
 * Используется хуками (useState, useMemo) для доступа к своему хранилищу состояния.
 * 
 * @returns {Fiber|null} - Текущий Fiber-узел или null, если нет активного контекста
 */
export function getCurrentFiber() {
  return currentFiber;
}

/**
 * Поверхностное сравнение двух объектов.
 * 
 * Проверяет, равны ли объекты по ссылке или имеют одинаковые ключи с одинаковыми значениями.
 * НЕ выполняет глубокое сравнение вложенных объектов.
 * 
 * Используется для быстрого сравнения пропсов компонента.
 * 
 * @param {Object} a - Первый объект для сравнения
 * @param {Object} b - Второй объект для сравнения
 * @returns {boolean} - true, если объекты равны поверхностно
 */
export function shallowEqual(a, b) {
    // Если это одна и та же ссылка - объекты точно равны
    if (a === b) return true;
    
    // Если один из объектов null/undefined - они не равны
    if (!a || !b) return false;
  
    // Получаем ключи обоих объектов
    const aKeys = Object.keys(a);
    const bKeys = Object.keys(b);
    
    // Если разное количество ключей - объекты не равны
    if (aKeys.length !== bKeys.length) return false;
  
    // Проверяем, что все значения по одинаковым ключам равны
    for (const k of aKeys) {
      // Сравниваем по ссылке (не глубоко!)
      if (a[k] !== b[k]) return false;
    }
    
    return true;
  }
  
  /**
   * Создает снимок (копию) массива хуков для последующего сравнения.
   * 
   * Используется для сохранения состояния хуков после успешного рендера.
   * При следующем рендере можно сравнить старый и новый снимок, чтобы определить,
   * изменились ли хуки (useState, useMemo).
   * 
   * Для useState в hooks[idx] лежит само значение (примитив или объект).
   * Для useMemo в hooks[idx] лежит объект { value, deps }.
   * 
   * @param {Array} hooks - Массив хуков для копирования
   * @returns {Array} - Копия массива хуков
   */
  export function snapshotHooks(hooks) {
    // Создаем поверхностную копию массива
    // Важно: это копия массива, но элементы (объекты) остаются по ссылкам
    return hooks.slice();
  }
  
  /**
   * Сравнивает два массива хуков на равенство.
   * 
   * Используется для определения, изменились ли хуки компонента между рендерами.
   * Это ключевая проверка для оптимизации bailout - если хуки не изменились,
   * можно пропустить рендер компонента.
   * 
   * Поддерживает два типа хуков:
   * 1. useState - значение хранится напрямую (примитив или объект)
   * 2. useMemo - значение хранится как { value, deps }
   * 
   * @param {Array} prev - Предыдущий массив хуков (снимок после прошлого рендера)
   * @param {Array} next - Текущий массив хуков
   * @returns {boolean} - true, если хуки не изменились
   */
  export function hooksEqual(prev, next) {
    // Если это одна и та же ссылка - хуки точно равны
    if (prev === next) return true;
    
    // Если один из массивов отсутствует - хуки не равны
    if (!prev || !next) return false;
    
    // Если разная длина - хуки не равны (количество хуков изменилось)
    if (prev.length !== next.length) return false;
  
    // Сравниваем каждый хук по индексу
    for (let i = 0; i < prev.length; i++) {
      const a = prev[i]; // Предыдущее значение хука
      const b = next[i]; // Текущее значение хука
  
      // Простое сравнение по ссылке - если ссылки равны, хук не изменился
      if (a === b) continue;
  
      // Специальная обработка для useMemo: { value, deps }
      // Если оба значения - объекты с полем deps, сравниваем их содержимое
      if (a && b && typeof a === 'object' && typeof b === 'object') {
        const aDeps = a.deps;
        const bDeps = b.deps;
        
        // Если оба имеют массив зависимостей - это useMemo
        if (Array.isArray(aDeps) && Array.isArray(bDeps)) {
          // Сравниваем значение
          if (a.value !== b.value) return false;
          
          // Сравниваем длину массива зависимостей
          if (aDeps.length !== bDeps.length) return false;
          
          // Сравниваем каждую зависимость
          for (let d = 0; d < aDeps.length; d++) {
            if (aDeps[d] !== bDeps[d]) return false;
          }
          
          // useMemo не изменился - переходим к следующему хуку
          continue;
        }
      }
  
      // Если дошли сюда - хуки не равны
      return false;
    }
  
    // Все хуки равны
    return true;
  }
  
  /**
   * Помечает Fiber-узел как "грязный" (требующий рендеринга).
   * 
   * Вызывается при изменении состояния компонента (например, через setState).
   * Также помечает всех родителей как имеющих "грязных" детей (childDirty = true).
   * 
   * Это позволяет:
   * 1. Отслеживать, какие компоненты нужно перерендерить
   * 2. Оптимизировать рендеринг родителей - если у родителя childDirty = true,
   *    но его собственные пропсы не изменились, он все равно должен рендериться,
   *    чтобы обновить дочерние компоненты
   * 
   * @param {Fiber} fiber - Fiber-узел, который нужно пометить как грязный
   */
  export function markFiberDirty(fiber) {
    // Помечаем сам узел как требующий рендеринга
    fiber.dirty = true;
    
    // Поднимаемся вверх по дереву и помечаем всех родителей
    // как имеющих "грязных" детей
    let p = fiber.parent;
    while (p) {
      p.childDirty = true;
      p = p.parent;
    }
  }
  
  /**
   * Проверяет, можно ли пропустить рендер компонента (bailout оптимизация).
   * 
   * Компонент можно пропустить, если:
   * 1. Сам компонент не помечен как "грязный" (dirty = false)
   * 2. Нет "грязных" детей (childDirty = false)
   * 3. Пропсы не изменились (shallowEqual)
   * 4. Хуки не изменились (hooksEqual)
   * 
   * Если все условия выполнены, можно вернуть мемоизированный vnode
   * без повторного вызова функции компонента.
   * 
   * Это важная оптимизация производительности - позволяет избежать
   * ненужных рендеров компонентов, которые не изменились.
   * 
   * @param {Fiber} fiber - Fiber-узел компонента для проверки
   * @param {Object} nextProps - Новые пропсы, которые будут переданы компоненту
   * @returns {boolean} - true, если можно пропустить рендер (bailout)
   */
  export function shouldBailout(fiber, nextProps) {
    // Если компонент помечен как "грязный" - рендер обязателен
    if (fiber.dirty) return false;
    
    // Если есть "грязные" дети - рендер обязателен (нужно обновить дочерние компоненты)
    if (fiber.childDirty) return false;
  
    // Если пропсы изменились - рендер обязателен
    // Сравниваем мемоизированные пропсы (после прошлого рендера) с новыми
    if (!shallowEqual(fiber.memoizedProps, nextProps)) return false;
    
    // Если хуки изменились - рендер обязателен
    // Сравниваем мемоизированные хуки (после прошлого рендера) с текущими
    if (!hooksEqual(fiber.memoizedHooks, fiber.hooks)) return false;
  
    // Все проверки пройдены - можно пропустить рендер!
    return true;
  }
  
  /**
   * Сохраняет мемоизированные значения после успешного рендера компонента.
   * 
   * Вызывается после того, как компонент успешно отрендерился.
   * Сохраняет "снимок" текущего состояния (пропсы, хуки, vnode) для использования
   * при следующем рендере для оптимизации bailout.
   * 
   * Также сбрасывает флаги dirty и childDirty, так как компонент только что
   * был отрендерен и теперь "чистый".
   * 
   * @param {Fiber} fiber - Fiber-узел компонента
   * @param {Object} props - Пропсы, которые были использованы при рендере
   * @param {Object} vnode - Виртуальный узел, возвращенный компонентом
   */
  export function commitFiberMemo(fiber, props, vnode) {
    // Сохраняем пропсы, которые были использованы при этом рендере
    // Они будут сравниваться с новыми пропсами при следующем рендере
    fiber.memoizedProps = props;
    
    // Сохраняем снимок текущих хуков
    // Это позволит сравнить их с новыми хуками при следующем рендере
    fiber.memoizedHooks = snapshotHooks(fiber.hooks);
    
    // Сохраняем виртуальный узел, возвращенный компонентом
    // Если при следующем рендере можно сделать bailout, вернем этот vnode
    fiber.memoizedVNode = vnode;
  
    // Сбрасываем флаги "грязности" - компонент только что был отрендерен
    fiber.dirty = false;        // Сам компонент "чистый"
    fiber.childDirty = false;   // Дети тоже "чистые" (пока не изменятся)
  }

/**
 * Класс Fiber - представляет узел в дереве компонентов.
 * 
 * Каждый экземпляр компонента имеет свой Fiber-узел, который хранит:
 * - Состояние компонента (массив хуков)
 * - Связи с другими узлами в дереве (parent, child, sibling)
 * - Метаданные для reconciliation (сопоставления старого и нового дерева)
 * 
 * Ключевое отличие от оригинальной реализации:
 * Состояние хранится в Fiber-узле, а не в глобальной Map по функции компонента.
 * Это позволяет использовать один компонент несколько раз с независимым состоянием.
 */
export class Fiber {
  /**
   * Создает новый Fiber-узел.
   * 
   * @param {Function|string} type - Тип узла (функция компонента или строка для DOM-элемента)
   * @param {Object} props - Пропсы, переданные компоненту
   * @param {Fiber|null} parent - Родительский Fiber-узел в дереве
   * @param {string|null} key - Ключ для оптимизации reconciliation (опционально)
   */
  constructor(type, props, parent = null, key = null) {
    // Флаг: этот узел требует ререндеринга 
    // (setState, новое свойство или force update)
    this.dirty = false;

    // Флаг: какой-то из дочерних компонентов требует ререндеринга 
    // (используется для оптимизации пропуска рендера родителей)
    this.childDirty = false;
    
    // Кэш последних "разрешённых" пропсов после успешного рендера 
    // (для сравнения при следующих рендерах)
    this.memoizedProps = null;

    // Кэш последних хранилищ хуков (useState/ useMemo); 
    // для сравнения "а не изменилось ли что-то"
    this.memoizedHooks = null;

    // Кэш последнего возвращённого vnode — позволяет быстро вернуть прошлый результат 
    // без повторного вызова render-функции
    this.memoizedVNode = null;

    // Основные свойства узла
    this.type = type;           // Функция компонента или строка (tag name)
    this.props = props;          // Пропсы компонента
    this.parent = parent;        // Ссылка на родительский Fiber-узел
    this.key = key;              // Ключ для reconciliation (помогает сопоставлять узлы)

    // Хранилище состояния компонента
    // КЛЮЧЕВОЙ МОМЕНТ: каждый экземпляр компонента имеет свой массив хуков!
    this.hooks = [];             // Массив для хранения значений хуков (useState, useMemo и т.д.)
    this.hookIndex = 0;          // Индекс текущего хука при рендеринге (сбрасывается на 0 для каждого рендера)

    // Структура дерева Fiber-узлов
    // Используется для навигации по дереву и reconciliation
    this.child = null;           // Ссылка на первый дочерний Fiber-узел
    this.sibling = null;         // Ссылка на следующий sibling (братский) узел на том же уровне

    // Внутренние поля для reconciliation (сопоставления старого и нового дерева)
    // Используются только во время рендеринга, не являются частью публичного API
    
    // Курсор для прохода по старым дочерним узлам при reconciliation
    // Помогает переиспользовать существующие Fiber-узлы при повторных рендерах
    this._oldCursor = null;
    
    // Указатель на последний добавленный дочерний узел (work in progress tail)
    // Используется для быстрого добавления новых дочерних узлов в конец списка (O(1))
    this._wipTail = null;
  }
}